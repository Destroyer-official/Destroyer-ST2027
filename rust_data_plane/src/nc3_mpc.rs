/// Magic header for NC3 MPC threshold signature wire packages.
pub const MPC_WIRE_MAGIC: &[u8; 10] = b"NC3-MPC-T1";

/// Maximum allowable temporal skew between physical silo signatures (2.0 seconds / 2000 ms).
/// Enforces DoD Directive S-5210.41M simultaneous co-signing invariant.
pub const MAX_TEMPORAL_SKEW_MILLIS: u64 = 2000;

/// Cryptographic domain separation string for NC3 MPC Threshold EAM.
pub const NC3_MPC_DOMAIN: &[u8] = b"DESTROYER-NC3-MPC-THRESHOLD-MLDSA87-V1";

/// Maximum allowable freshness window for an EAM directive (120 seconds).
pub const EAM_FRESHNESS_WINDOW_SECS: u64 = 120;

/// SHA-384 digest length in bytes (CNSA 2.0).
pub const SHA384_DIGEST_LEN: usize = 48;

/// Minimum wire envelope length:
/// [magic: 10B][threshold: 2B][skew: 8B][digest: 48B][agg_sig: 48B][vss: 48B][meta_len: 4B]
pub const MIN_MPC_WIRE_LEN: usize = 10 + 2 + 8 + 48 + 48 + 48 + 4;

/// Verifiable Secret Sharing Share of the master strategic authorization secret.
#[derive(Debug, Clone, Zeroize)]
#[zeroize(drop)]
pub struct MpcSiloShare {
    pub share_index: u32,
    pub share_bytes: Vec<u8>,
    pub share_commitment: [u8; SHA384_DIGEST_LEN],
    pub master_commitment: [u8; SHA384_DIGEST_LEN],
    pub salt: [u8; 32],
}

impl MpcSiloShare {
    /// Create and verify a new silo share against its SHA-384 Feldman commitment.
    pub fn new(
        share_index: u32,
        share_bytes: Vec<u8>,
        share_commitment: [u8; SHA384_DIGEST_LEN],
        master_commitment: [u8; SHA384_DIGEST_LEN],
        salt: [u8; 32],
    ) -> Result<Self, CoreError> {
        if share_index == 0 || share_bytes.is_empty() {
            return Err(CoreError::Malformed);
        }
        let share = Self {
            share_index,
            share_bytes,
            share_commitment,
            master_commitment,
            salt,
        };
        share.verify_commitment()?;
        Ok(share)
    }

    /// Verify this share's internal commitment using constant-time evaluation.
    pub fn verify_commitment(&self) -> Result<(), CoreError> {
        let mut hasher = Sha384::new();
        hasher.update(b"NC3-FELDMAN-SHA384-SHARE-V1:");
        hasher.update(self.salt);
        hasher.update(self.share_index.to_be_bytes());
        hasher.update(&self.share_bytes);
        let calculated = hasher.finalize();

        if ct_eq(&calculated, &self.share_commitment) {
            Ok(())
        } else {
            Err(CoreError::BadSignature)
        }
    }
}

